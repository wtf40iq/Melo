const dicts: Record<Lang, Record<string, string>> = { ru: {}, en };

export function translate(lang: Lang, key: string, params?: Record<string, string | number>) {
  let s = dicts[lang][key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** «12 треков» / «12 tracks» */
export function tracksLabel(lang: Lang, n: number) {
  if (lang === "en") return `${n} ${n === 1 ? "track" : "tracks"}`;
  const m10 = n % 10, m100 = n % 100;
  const w = m10 === 1 && m100 !== 11 ? "трек" : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? "трека" : "треков";
  return `${n} ${w}`;
}
